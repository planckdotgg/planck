//go:build darwin

package clipboard

import (
	"context"
	"runtime"
	"sync"
	"time"
	"unsafe"

	"github.com/ebitengine/purego"
	"github.com/ebitengine/purego/objc"
)

var appKitOnce sync.Once

func loadAppKit() {
	appKitOnce.Do(func() {
		_, _ = purego.Dlopen("/System/Library/Frameworks/AppKit.framework/AppKit", purego.RTLD_NOW|purego.RTLD_GLOBAL)
	})
}

const (
	pollInterval     = 200 * time.Millisecond
	typeText         = "public.utf8-plain-text"
	typePNG          = "public.png"
	typeTIFF         = "public.tiff"
	utf8Encoding     = 4
	bitmapPNGType    = 4
	bitmapTIFFNoComp = 1
)

// skipTypes mark content that clipboard tools should not record or share
// (nspasteboard.org): password managers set ConcealedType.
var skipTypes = []string{"org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"}

func sel(s string) objc.SEL { return objc.RegisterName(s) }

func class(name string) objc.ID { return objc.ID(objc.GetClass(name)) }

func nsString(s string) objc.ID {
	b := []byte(s)
	var p unsafe.Pointer
	if len(b) > 0 {
		p = unsafe.Pointer(&b[0])
	}
	str := class("NSString").Send(sel("alloc")).Send(sel("initWithBytes:length:encoding:"), p, len(b), utf8Encoding)
	runtime.KeepAlive(b)
	return str.Send(sel("autorelease"))
}

func nsData(b []byte) objc.ID {
	var p unsafe.Pointer
	if len(b) > 0 {
		p = unsafe.Pointer(&b[0])
	}
	d := class("NSData").Send(sel("dataWithBytes:length:"), p, len(b))
	runtime.KeepAlive(b)
	return d
}

func goBytes(data objc.ID) []byte {
	n := objc.Send[int](data, sel("length"))
	if n == 0 {
		return []byte{}
	}
	p := objc.Send[unsafe.Pointer](data, sel("bytes"))
	return append([]byte(nil), unsafe.Slice((*byte)(p), n)...)
}

// withPool runs fn on a locked thread inside an autorelease pool.
func withPool(fn func()) {
	runtime.LockOSThread()
	defer runtime.UnlockOSThread()
	pool := class("NSAutoreleasePool").Send(sel("new"))
	defer pool.Send(sel("drain"))
	fn()
}

// pasteboard is an NSPasteboard: the general one, or a named one in tests.
type pasteboard struct {
	name string

	mu     sync.Mutex
	cancel context.CancelFunc
	done   chan struct{}
}

func openBoard() (Board, error) {
	loadAppKit()
	return &pasteboard{}, nil
}

func (p *pasteboard) pb() objc.ID {
	if p.name == "" {
		return class("NSPasteboard").Send(sel("generalPasteboard"))
	}
	return class("NSPasteboard").Send(sel("pasteboardWithName:"), nsString(p.name))
}

func (p *pasteboard) changeCount() (n int) {
	withPool(func() { n = objc.Send[int](p.pb(), sel("changeCount")) })
	return n
}

func (p *pasteboard) Read() (it Item, ok bool, err error) {
	withPool(func() { it, ok = p.read() })
	return it, ok, nil
}

// read must run inside withPool.
func (p *pasteboard) read() (Item, bool) {
	pb := p.pb()
	types := pb.Send(sel("types"))
	if types == 0 {
		return Item{}, false
	}
	for _, t := range skipTypes {
		if objc.Send[bool](types, sel("containsObject:"), nsString(t)) {
			return Item{}, false
		}
	}
	if s := pb.Send(sel("stringForType:"), nsString(typeText)); s != 0 {
		n := objc.Send[int](s, sel("lengthOfBytesUsingEncoding:"), utf8Encoding)
		if n > MaxSize {
			return Item{Format: Text, Size: n}, true
		}
		data := s.Send(sel("dataUsingEncoding:"), utf8Encoding)
		b := goBytes(data)
		return Item{Format: Text, Data: b, Size: len(b)}, true
	}
	if d := pb.Send(sel("dataForType:"), nsString(typePNG)); d != 0 {
		if n := objc.Send[int](d, sel("length")); n > MaxSize {
			return Item{Format: PNG, Size: n}, true
		}
		b := goBytes(d)
		return Item{Format: PNG, Data: b, Size: len(b)}, true
	}
	if d := pb.Send(sel("dataForType:"), nsString(typeTIFF)); d != 0 {
		rep := class("NSBitmapImageRep").Send(sel("imageRepWithData:"), d)
		if rep == 0 {
			return Item{}, false
		}
		png := rep.Send(sel("representationUsingType:properties:"), bitmapPNGType, class("NSDictionary").Send(sel("dictionary")))
		if png == 0 {
			return Item{}, false
		}
		if n := objc.Send[int](png, sel("length")); n > MaxSize {
			return Item{Format: PNG, Size: n}, true
		}
		b := goBytes(png)
		return Item{Format: PNG, Data: b, Size: len(b)}, true
	}
	return Item{}, false
}

// Write puts it on the pasteboard; an image also goes up as TIFF for apps
// that read only that.
func (p *pasteboard) Write(it Item) error {
	if len(it.Data) > MaxSize {
		return ErrTooLarge
	}
	if it.Format != Text && it.Format != PNG {
		return ErrFormat
	}
	withPool(func() {
		pb := p.pb()
		pb.Send(sel("clearContents"))
		if it.Format == Text {
			str := class("NSString").Send(sel("alloc")).Send(sel("initWithData:encoding:"), nsData(it.Data), utf8Encoding).Send(sel("autorelease"))
			pb.Send(sel("setString:forType:"), str, nsString(typeText))
			return
		}
		data := nsData(it.Data)
		pb.Send(sel("setData:forType:"), data, nsString(typePNG))
		if rep := class("NSBitmapImageRep").Send(sel("imageRepWithData:"), data); rep != 0 {
			if tiff := rep.Send(sel("TIFFRepresentation")); tiff != 0 {
				pb.Send(sel("setData:forType:"), tiff, nsString(typeTIFF))
			}
		}
	})
	return nil
}

// Watch polls changeCount: macOS has no clipboard change notification.
func (p *pasteboard) Watch(ctx context.Context, onChange func(Item)) error {
	p.mu.Lock()
	if p.done != nil {
		p.mu.Unlock()
		return errWatching
	}
	ctx, p.cancel = context.WithCancel(ctx)
	done := make(chan struct{})
	p.done = done
	p.mu.Unlock()
	last := p.changeCount()
	go func() {
		defer close(done)
		t := time.NewTicker(pollInterval)
		defer t.Stop()
		for {
			select {
			case <-ctx.Done():
				return
			case <-t.C:
			}
			if n := p.changeCount(); n != last {
				last = n
				if it, ok, _ := p.Read(); ok {
					onChange(it)
				}
			}
		}
	}()
	go func() {
		<-done
		p.mu.Lock()
		p.done = nil
		p.mu.Unlock()
	}()
	return nil
}

func (p *pasteboard) Close() error {
	p.mu.Lock()
	cancel, done := p.cancel, p.done
	p.mu.Unlock()
	if cancel != nil {
		cancel()
	}
	if done != nil {
		<-done
	}
	return nil
}
